package com.example.Ece.agent.eco;

/**
 * 管理与经济参数（模型五）。
 *
 * <p><b>参数来源纪律</b>：本类中的价格均为**示例参数**，用于演示"AI 决策 → 成本收益"的换算链路；
 * 正式参赛材料必须替换为当地实际价格并标注来源与日期（农资店报价、批发市场均价、当地电价文件等），
 * 否则只能标注为示例，不得声称经济效益来自实测经营数据。</p>
 */
public final class EconomicsParameters {

    /** 每亩面积（m²）。标准里灌溉定额的分母写作 667 m²。 */
    private static final double SQUARE_METERS_PER_MU = 667.0;


    private EconomicsParameters() {
    }

    /**
     * 灌溉水价（元/m³）。
     *
     * <p><b>2026-09-26 按实价替换，原示例值 3.5 高估约 4 倍。</b>
     * 依据：山东寿光《农业水价综合改革项目区用水终端价格指导意见》——**设施农业用水执行完全成本价**，
     * 指导区间 **0.46~0.95 元/m³**；河南渑池井灌区经济作物定额内 0.8 元/m³。
     * 取 **0.8**（区间中位偏上，因设施农业多用井灌/提水）。</p>
     *
     * <p><b>未建模的真实机制</b>：各省普遍实行**超定额累进加价**（山东超 50% 以内按 1.5 倍、
     * 以上按 2 倍；河南超 20% 以内加 30%、以上加 100%）。本模型按单一水价计，
     * 因而**低估了过量灌溉的边际成本**——这与"节水"主题直接相关，属待补机制。</p>

    /**
     * 农业生产用电电价（元/kWh）。
     *
     * <p><b>2026-09-26 按实价替换。</b>依据各省农业生产用电到户电价表：
     * 甘肃 1-10 千伏平段 **0.4389**（峰 0.6564 / 谷 0.2215）、陕西子洲 1-10 千伏平段 **0.4728**、
     * 江西单一制 **0.6534**。取 **0.4389**（1-10 千伏**平段**）；峰、谷见下方两个常量与 energyPriceAt。</p>
     *
     * <p><b>未建模的真实机制</b>：农业用电**分峰谷**，峰谷价差可达 3 倍。
     * 而温室设备的运行时段与峰谷高度相关（补光多在后半夜、湿帘在白天高温段），
     * 按单一电价计会**同时低估与高估**不同策略的电费。属待补机制。</p>
     *
     * <p>注意 0.65 恰是江西的单一制电价，且原注释未说明来源——示例值碰巧接近上界。</p>

    /** CO₂ 气源成本（元/kg）。示例参数。 */
    public static final double ENERGY_YUAN_PER_KWH = 0.4389;

    /**
     * 农业生产用电**高峰**电价（元/kWh）。
     *
     * <p>出处同 {@link #ENERGY_YUAN_PER_KWH}（甘肃电网农业生产用电到户电价表，1-10 千伏）。</p>
     */
    public static final double ENERGY_PEAK_YUAN_PER_KWH = 0.6564;

    /** 农业生产用电**低谷**电价（元/kWh）。出处同上。 */
    public static final double ENERGY_VALLEY_YUAN_PER_KWH = 0.2215;

    /**
     * 灌溉定额（m³/667m²，**秋冬茬**）。
     *
     * <p>出处：DB37/T 1849—2026《日光温室番茄水肥一体化生产技术规程》7.1——
     * "秋冬茬灌溉定额为 129 m³/667m²，冬春茬灌溉定额 146 m³/667m²"。
     * 取秋冬茬值：本模型的评测季从 9 月下旬起，与秋冬茬最接近（DB37 未给茬口日历，
     * 茬口归属按 DB12/T 1044 的茬口定义判断，属本项目判断而非标准原文）。</p>
     */
    public static final double WATER_QUOTA_M3_PER_667M2 = 129.0;

    /** 超定额累进加价的档位倍数（山东口径）：超定额 50% 以内 1.5 倍、以上 2 倍。 */
    private static final double WATER_TIER2_MULTIPLIER = 1.5;

    /** 超定额 50% 以上的倍数。 */
    private static final double WATER_TIER3_MULTIPLIER = 2.0;

    /**
     * 按**累计**用水量取灌溉水价（超定额累进加价）。
     *
     * <p><b>2026-09-26 新增。</b>此前按单一水价计，**低估了过量灌溉的边际成本**——
     * 而这与"节水"主题直接相关。各省普遍实行超定额累进加价：
     * 山东超定额 50% 以内按 1.5 倍、50% 以上按 2 倍（本实现取此口径）；
     * 河南为超 20% 以内加 30%、以上加 100%。</p>
     *
     * <p><b>接入后暴露的第一个事实</b>：本模型的规则层（P2/P3）用水达定额的 **3.15~3.24 倍**，
     * 而定时盲灌（P1）反而是 **1.04 倍**。也就是说**按墒情灌溉的"智能"档比定时盲灌多浇三倍水**。
     * 该事实在单一水价下完全看不见——每立方米都一样贵，浇多浇少只是线性差距。</p>
     *
     * <p><b>为什么按累计量取价而不是按步用量</b>：累进加价的语义是**边际**价格随累计用量上升，
     * 因此应当用"本步之前已用多少"来决定本步的单价，而不是用本步用量。</p>
     *
     * @param cumulativeM3 本步**之前**的累计灌溉量（m³）
     */
    public static double waterPriceAt(double cumulativeM3) {
        double quota = waterQuotaM3();
        if (cumulativeM3 <= quota) {
            return WATER_YUAN_PER_M3;
        }
        if (cumulativeM3 <= quota * WATER_TIER2_MULTIPLIER) {
            return WATER_YUAN_PER_M3 * WATER_TIER2_MULTIPLIER;
        }
        return WATER_YUAN_PER_M3 * WATER_TIER3_MULTIPLIER;
    }

    /** 本模型种植床面积折合的一季灌溉定额（m³）。 */
    public static double waterQuotaM3() {
        return WATER_QUOTA_M3_PER_667M2 * SoilParameters.BED_AREA_M2 / SQUARE_METERS_PER_MU;
    }

    /**
     * 按钟点取农业生产用电电价（分时）。
     *
     * <p><b>2026-09-26 新增。</b>此前全模型按单一电价计电费，而农业用电**是分时的**，
     * 峰谷价差在甘肃口径下达 **3 倍**（0.6564 / 0.2215）。这不只是"算得准不准"的问题——
     * 它**改变不同策略之间的排序**：温室设备的运行时段与峰谷高度相关，而不同策略的设备组合不同。</p>
     *
     * <p><b>时段划分</b>（甘肃省发改委 甘发改价格〔2024〕424号，2024-08-01 起执行，
     * 适用于农业生产电力用户、农业排灌除外）：高峰 6:00-8:00 与 18:00-23:00（7 小时）；
     * 平段 23:00-6:00、8:00-10:00、16:00-18:00（11 小时）；**低谷 10:00-16:00（6 小时，午间低谷）**。</p>
     *
     * <p><b>对本模型的含义（值得单独说）</b>：这套划分是**光伏消纳**驱动的"午间谷电"，
     * 与直觉相反——**补光常落在 18:00-23:00 的高峰，而湿帘降温落在 10:00-16:00 的低谷**。
     * 也就是说分时电价会同时**惩罚补光、补贴白天降温**，与按平段计价相比，
     * 不同策略的电费差距会被拉开而不是抹平。</p>
     *
     * <p><b>跨省不可照搬</b>：各省时段划分不同（有的低谷在夜间），换场地必须同时换时段与电价。</p>
     */
    public static double energyPriceAt(int hourOfDay) {
        int hour = ((hourOfDay % 24) + 24) % 24;
        if ((hour >= 6 && hour < 8) || (hour >= 18 && hour < 23)) {
            return ENERGY_PEAK_YUAN_PER_KWH;
        }
        if (hour >= 10 && hour < 16) {
            return ENERGY_VALLEY_YUAN_PER_KWH;
        }
        return ENERGY_YUAN_PER_KWH;
    }
    public static final double WATER_YUAN_PER_M3 = 0.8;
    public static final double CO2_YUAN_PER_KG = 1.2;

    /**
     * 肥料成本（元/kg）。
     *
     * <p><b>2026-09-26 按实价替换。</b>依据 2026 年农资监测：45%(15-15-15) 复合肥
     * 氯基出厂 **2650~2950 元/吨**（硫基 3100~3500）；尿素 1745~1895 元/吨。
     * 取 **2.9 元/kg**（45% 氯基复合肥，与 {@code FERTILIZER_NITROGEN_SHARE = 0.15}
     * 所隐含的 15-15-15 口径一致）。</p>
     *
     * <p><b>若改用管道给的标准里推荐的水溶肥，本值偏低</b>：60%(20-20-20) 大量元素水溶肥
     * 出厂 6000~8000 元/吨（6~8 元/kg），是复合肥的 2~3 倍。两者不是同一口径，
     * 换肥料形态时此值必须同步换。</p>

    /** 植保药剂成本（元/kg）。示例参数。 */
    public static final double FERTILIZER_YUAN_PER_KG = 2.9;
    public static final double PESTICIDE_YUAN_PER_KG = 60.0;

    /**
     * 人工成本（元/工时）。
     *
     * <p><b>2026-09-26 按实价替换，原值 25.0 高估约一倍。</b>依据 2026 年用工采购与调查：
     * 四川遂宁集体经济组织栽种 60 元/天、除草打药 80 元/天、人工管理 100 元/天（均按 8 小时）；
     * 农忙雇工 200 元/天；海南农垦设施园艺 176~330 元/天。
     * 取 **12.5 元/工时**（= 100 元/天 ÷ 8 小时，设施园艺技术工口径）。</p>

    /** 固定摊销成本（元/天：设施折旧、管理、水电基础费）。示例参数。 */
    public static final double LABOR_YUAN_PER_HOUR = 12.5;
    public static final double FIXED_COST_YUAN_PER_DAY = 20.0;

    /**
     * 一等品收购价（元/kg）。
     *
     * <p><b>2026-09-26 按实价核对后上调至 7.0。</b>依据：山东聊城设施大棚产地批发
     * **3.5 元/斤 = 7 元/kg**（阳谷 2.5~3.8 元/斤）；农业农村部 2026 年 1 月全国西红柿
     * 批发均价 **8.61 元/kg**（同比 +80.9%，属减产推高的高位年份）。</p>
     *
     * <p><b>本参数波动极大</b>：2026-09-25 各产地批发市场 2.10~8.00 元/kg（成都产 3.00~5.40）。
     * 取 7.0 反映**产地收购**口径与 2026 年高位；跨年份对比时须同步换价，否则"利润"不可比。</p>

    /** 二等品收购价（元/kg）。2026-09-26 按一等品的半价惯例随之上调至 3.5。示例参数。 */
    public static final double GRADE_A_PRICE_YUAN_PER_KG = 7.0;
    public static final double GRADE_B_PRICE_YUAN_PER_KG = 3.5;

    /** 一等品比例。示例参数，需按实际分级结果核对。 */
    public static final double GRADE_A_RATIO = 0.7;

    /** 番茄果实干物质率（干重/鲜重）。典型区间 5%–6%，用于把模型输出的果实干重折算为鲜重产量。 */
    public static final double FRUIT_DRY_MATTER_FRACTION = 0.055;

}
