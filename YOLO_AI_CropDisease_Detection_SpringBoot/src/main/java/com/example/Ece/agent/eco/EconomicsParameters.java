package com.example.Ece.agent.eco;

/**
 * 管理与经济参数（模型五）。
 *
 * <p><b>参数来源纪律</b>：本类中的价格均为**示例参数**，用于演示"AI 决策 → 成本收益"的换算链路；
 * 正式参赛材料必须替换为当地实际价格并标注来源与日期（农资店报价、批发市场均价、当地电价文件等），
 * 否则只能标注为示例，不得声称经济效益来自实测经营数据。</p>
 */
public final class EconomicsParameters {

    private EconomicsParameters() {
    }

    /**
     * 灌溉水价（元/m³）。
     *
     * <p><b>2026-09-26 按实价替换，原示例值 3.5 高估约 4 倍。</b>
     * 依据：山东寿光《农业水价综合改革项目区用水终端价格指导意见》——**设施农业用水执行完全成本价**，
     * 指导区间 **0.46~0.95 元/m³**；河南渑池井灌区经济作物定额内 0.8 元/m³。
     * 取 **0.8**（区间中位偏上，因设施农业多用井灌/提水）。</p>
     *
     * <p><b>未建模的真实机制</b>：各省普遍实行**超定额累进加价**（山东超 50% 以内按 1.5 倍、
     * 以上按 2 倍；河南超 20% 以内加 30%、以上加 100%）。本模型按单一水价计，
     * 因而**低估了过量灌溉的边际成本**——这与"节水"主题直接相关，属待补机制。</p>

    /**
     * 农业生产用电电价（元/kWh）。
     *
     * <p><b>2026-09-26 按实价替换。</b>依据各省农业生产用电到户电价表：
     * 甘肃 1-10 千伏平段 **0.4389**（峰 0.6564 / 谷 0.2215）、陕西子洲 1-10 千伏平段 **0.4728**、
     * 江西单一制 **0.6534**。取 **0.47**（1-10 千伏平段）。</p>
     *
     * <p><b>未建模的真实机制</b>：农业用电**分峰谷**，峰谷价差可达 3 倍。
     * 而温室设备的运行时段与峰谷高度相关（补光多在后半夜、湿帘在白天高温段），
     * 按单一电价计会**同时低估与高估**不同策略的电费。属待补机制。</p>
     *
     * <p>注意 0.65 恰是江西的单一制电价，且原注释未说明来源——示例值碰巧接近上界。</p>

    /** CO₂ 气源成本（元/kg）。示例参数。 */
    public static final double ENERGY_YUAN_PER_KWH = 0.47;
    public static final double WATER_YUAN_PER_M3 = 0.8;
    public static final double CO2_YUAN_PER_KG = 1.2;

    /**
     * 肥料成本（元/kg）。
     *
     * <p><b>2026-09-26 按实价替换。</b>依据 2026 年农资监测：45%(15-15-15) 复合肥
     * 氯基出厂 **2650~2950 元/吨**（硫基 3100~3500）；尿素 1745~1895 元/吨。
     * 取 **2.9 元/kg**（45% 氯基复合肥，与 {@code FERTILIZER_NITROGEN_SHARE = 0.15}
     * 所隐含的 15-15-15 口径一致）。</p>
     *
     * <p><b>若改用管道给的标准里推荐的水溶肥，本值偏低</b>：60%(20-20-20) 大量元素水溶肥
     * 出厂 6000~8000 元/吨（6~8 元/kg），是复合肥的 2~3 倍。两者不是同一口径，
     * 换肥料形态时此值必须同步换。</p>

    /** 植保药剂成本（元/kg）。示例参数。 */
    public static final double FERTILIZER_YUAN_PER_KG = 2.9;
    public static final double PESTICIDE_YUAN_PER_KG = 60.0;

    /**
     * 人工成本（元/工时）。
     *
     * <p><b>2026-09-26 按实价替换，原值 25.0 高估约一倍。</b>依据 2026 年用工采购与调查：
     * 四川遂宁集体经济组织栽种 60 元/天、除草打药 80 元/天、人工管理 100 元/天（均按 8 小时）；
     * 农忙雇工 200 元/天；海南农垦设施园艺 176~330 元/天。
     * 取 **12.5 元/工时**（= 100 元/天 ÷ 8 小时，设施园艺技术工口径）。</p>

    /** 固定摊销成本（元/天：设施折旧、管理、水电基础费）。示例参数。 */
    public static final double LABOR_YUAN_PER_HOUR = 12.5;
    public static final double FIXED_COST_YUAN_PER_DAY = 20.0;

    /**
     * 一等品收购价（元/kg）。
     *
     * <p><b>2026-09-26 按实价核对后上调至 7.0。</b>依据：山东聊城设施大棚产地批发
     * **3.5 元/斤 = 7 元/kg**（阳谷 2.5~3.8 元/斤）；农业农村部 2026 年 1 月全国西红柿
     * 批发均价 **8.61 元/kg**（同比 +80.9%，属减产推高的高位年份）。</p>
     *
     * <p><b>本参数波动极大</b>：2026-09-25 各产地批发市场 2.10~8.00 元/kg（成都产 3.00~5.40）。
     * 取 7.0 反映**产地收购**口径与 2026 年高位；跨年份对比时须同步换价，否则"利润"不可比。</p>

    /** 二等品收购价（元/kg）。2026-09-26 按一等品的半价惯例随之上调至 3.5。示例参数。 */
    public static final double GRADE_A_PRICE_YUAN_PER_KG = 7.0;
    public static final double GRADE_B_PRICE_YUAN_PER_KG = 3.5;

    /** 一等品比例。示例参数，需按实际分级结果核对。 */
    public static final double GRADE_A_RATIO = 0.7;

    /** 番茄果实干物质率（干重/鲜重）。典型区间 5%–6%，用于把模型输出的果实干重折算为鲜重产量。 */
    public static final double FRUIT_DRY_MATTER_FRACTION = 0.055;

}
