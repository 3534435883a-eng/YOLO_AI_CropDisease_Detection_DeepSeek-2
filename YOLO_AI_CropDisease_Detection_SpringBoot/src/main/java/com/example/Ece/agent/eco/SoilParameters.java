    public static final double NUTRIENT_CUMULATIVE_SHARE_AT_FLOWERING = 0.1868;

    /** 坐果后期累计吸氮比例。出处同上。 */
    public static final double NUTRIENT_CUMULATIVE_SHARE_AT_LATE_FRUIT_SET = 0.6808;

