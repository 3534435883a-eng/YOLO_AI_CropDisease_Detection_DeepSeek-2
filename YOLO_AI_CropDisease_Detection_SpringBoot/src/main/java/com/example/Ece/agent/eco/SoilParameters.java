package com.example.Ece.agent.eco;

/**
 * 番茄温室土壤水分—养分模型参数表（模型 1）。
 *
 * <p>下列常数取自三类文献族：</p>
 * <ul>
 *   <li><b>FAO-56 番茄作物系数</b>：以参考蒸散 ET0 乘作物系数 Kc 得到作物蒸散 ETc 的灌溉需水计算族。</li>
 *   <li><b>国内设施番茄栽培文献</b>：日光温室/塑料大棚番茄的土壤水分管理、土壤养分丰缺指标、
 *       土壤 pH 适宜范围与灌溉制度相关文献族。</li>
 *   <li><b>国内设施番茄水肥一体化文献</b>：灌溉水与肥料带入的盐分（EC）累积与淋洗相关文献族。</li>
 * </ul>
 *
 * <p><b>数值说明：</b>本文件中的取值均为“典型文献区间，待核对出处”。
 * 这里刻意不写出具体论文标题、年份或页码，以避免引用不确切的出处。</p>
 *
 * <p>所有数值均为模拟用参数，<b>不代表任何实测数据</b>。</p>
 */
public final class SoilParameters {

    private SoilParameters() {
        // 常量类，禁止实例化
    }

    /** 各常数的文献族来源说明（供上层文档/接口展示，避免在代码中臆造具体出处）。 */
    public static final String[] SOURCE_NOTES = new String[] {
            "作物系数 Kc（初期/中期/后期）：FAO-56 番茄作物系数族；典型文献区间，待核对出处。",
            "单位干物质养分带走量（N/P/K）：国内设施番茄栽培文献；典型文献区间，待核对出处。",
            "肥料盐分换算系数与淋洗速率：国内设施番茄水肥一体化文献；典型文献区间，待核对出处。",
            "土壤 pH 适宜上下限：国内设施番茄栽培文献；典型文献区间，待核对出处。",
            "土壤速效养分丰缺阈值：国内设施番茄栽培文献；典型文献区间，待核对出处。",
            "田间持水量与凋萎点：国内设施番茄栽培文献；典型文献区间，待核对出处。",
            "单步灌溉量：国内设施番茄灌溉制度文献；典型文献区间，待核对出处。"
    };

    // ------------------------------------------------------------------
    // 作物系数（FAO-56 番茄作物系数）
    // ------------------------------------------------------------------

    /** 初期作物系数 Kc（苗期）。来源：番茄作物系数 FAO-56；典型文献区间，待核对出处。 */
    public static final double KC_INITIAL = 0.6;

    /** 中期作物系数 Kc（开花—坐果期）。来源：番茄作物系数 FAO-56；典型文献区间，待核对出处。 */
    public static final double KC_MID = 1.15;

    /** 后期作物系数 Kc（果实膨大—成熟期）。来源：番茄作物系数 FAO-56；典型文献区间，待核对出处。 */
    public static final double KC_LATE = 0.8;

    // ------------------------------------------------------------------
    // 单位干物质养分带走量（kg 养分 / kg 干物质）
    // ------------------------------------------------------------------

    /** 单位干物质氮带走量。来源：国内设施番茄栽培文献；典型文献区间，待核对出处。 */
    public static final double N_PER_KG_DM = 0.035;

    /** 单位干物质磷带走量。来源：国内设施番茄栽培文献；典型文献区间，待核对出处。 */
    public static final double P_PER_KG_DM = 0.008;

    /** 单位干物质钾带走量。来源：国内设施番茄栽培文献；典型文献区间，待核对出处。 */
    public static final double K_PER_KG_DM = 0.045;

    // ------------------------------------------------------------------
    // 肥料盐分与淋洗
    // ------------------------------------------------------------------

    /** 每 kg/ha 肥料带来的 EC 增量（dS/m）。来源：国内设施番茄水肥一体化文献；典型文献区间，待核对出处。 */
    public static final double EC_PER_KG_FERT = 0.02;

    /** EC 淋洗/衰减速率（每天）。来源：国内设施番茄水肥一体化文献；典型文献区间，待核对出处。 */
    public static final double EC_LEACH_RATE = 0.05;

    // ------------------------------------------------------------------
    // 土壤化学性质适宜范围
    // ------------------------------------------------------------------

    /** 土壤 pH 下限。来源：国内设施番茄栽培文献；典型文献区间，待核对出处。 */
    public static final double PH_MIN = 4.0;

    /** 土壤 pH 上限。来源：国内设施番茄栽培文献；典型文献区间，待核对出处。 */
    public static final double PH_MAX = 8.5;

    // ------------------------------------------------------------------
    // 土壤速效养分丰缺阈值（kg/ha）
    // ------------------------------------------------------------------

    /** 养分胁迫下限（低于此值养分因子取下限）。来源：国内设施番茄栽培文献；典型文献区间，待核对出处。 */
    public static final double NUTRIENT_LOW = 20.0;

    /** 养分充足上限（高于此值养分因子取 1.0）。来源：国内设施番茄栽培文献；典型文献区间，待核对出处。 */
    public static final double NUTRIENT_HIGH = 90.0; // 与 initial() 的 90 kg/ha 对齐：初始土壤即"养分充足"（因子 1.0），避免开局就吃 30% 养分惩罚

    // ------------------------------------------------------------------
    // 土壤水分特征常数
    // ------------------------------------------------------------------

    /** 田间持水量（%vol）。来源：国内设施番茄栽培文献；典型文献区间，待核对出处。 */
    public static final double FIELD_CAPACITY_PCT = 75.0;

    /** 凋萎点（%vol）。来源：国内设施番茄栽培文献；典型文献区间，待核对出处。 */
    public static final double WILTING_POINT_PCT = 30.0;

    /**
     * 种植床总面积（m²）：4 条 × 21 m × 1.7 m = 142.8 m²。
     *
     * <p>棚体本身是 26 m × 13 m（见 {@code docs/tomato-greenhouse-agent.md}），但作物只种在四条床上，
     * 因此**与作物相关的折算（单位面积产量、灌溉水深）都该用床面积而非棚体面积**。
     * 提取成常量是因为此前这个乘积被内联在灌溉量算式里，报告侧要再算一次单位面积产量时
     * 容易各写各的——面积这种几何数只能有一个定义。</p>
     */
    public static final double BED_AREA_M2 = 4.0 * 21.0 * 1.7;

    /**
     * 灌溉触发阈值：田间持水量的百分比。
     *
     * <p><b>2026-09-26 新增，取值 0.85 有出处</b>：马志军等《水氮互作对设施番茄土壤氮平衡及
     * 氮素利用效率的影响研究》，《北京水务》2024 年第 5 期，
     * DOI 10.19671/j.1673-4637.2024.05.002——该文结论为"设施番茄适宜土壤水分**灌水下限为田间持水量的 85%**"。
     * 论文同时给出灌水频率"每 7 d 左右 1 次"，与模型按此阈值推出来的周期量级一致。</p>
     *
     * <p>此前规则层用固定 45 %vol，相当于田间持水量（75 %vol）的 60%——**灌溉明显偏晚**，
     * 作物在灌前会经历水分胁迫（该胁迫机制此前因口径不一致而未被触发，修好后可见）。</p>
     */
    public static final double IRRIGATION_TRIGGER_FRACTION_OF_FC = 0.85;

    /**
     * 一季追肥总量（kg/hm²）。
     *
     * <p><b>2026-09-26 新增，取值 171 有出处</b>：同上论文——"适宜追肥量为 171 kg/hm²"。
     * 论文记载分 2 次追施（第 1 果直径 1.5~2.5 cm 时、第 2 果直径 2~3 cm 时），
     * 模型据此对齐到两个生育期节点（见 {@code PerformanceEvaluationService} 的施肥逻辑）。</p>
     *
     * <p>此前模型按每次灌溉施加 0.02 kg/ha，全季累计仅约 26.8 kg/ha——**比论文推荐值低约 6.4 倍**，
     * 是速效氮在季内见底、养分因子长期钳在下限的直接原因。</p>
     */
    public static final double SEASON_TOPDRESSING_KG_PER_HA = 171.0;

    /** 一季追肥的施用次数。论文记载为 2 次。 */
    public static final int TOPDRESSING_APPLICATIONS = 2;

    /**
     * 一次滴灌事件的水量（mm）。
     *
     * <p><b>2026-09-26 新增，取值 0.42 mm 是由项目自身参数推出的</b>，不是文献值：
     * 引擎 {@code IRRIGATION_L_PER_TICK = 60 L} 浇在 {@link #BED_AREA_M2} = 142.8 m² 种植床上，
     * 折合水深 60 / 142.8 = 0.4202 mm。用这个值是为了让土壤模型与引擎**浇同样多的水**——
     * 此前土壤模型按 {@code IRRIGATION_MM_PER_STEP}（注释写 mm/day）算，与引擎各浇各的，
     * 是两个水分状态能差到 49 个百分点的成因之一。</p>
     */
    public static final double IRRIGATION_MM_PER_EVENT = 60.0 / BED_AREA_M2;

    /**
     * 场地纬度（度）。FAO-56 计算日序天文辐射 Ra 需要它。
     *
     * <p>取 30.7°（成都）。**这是项目所在地的示例取值，不是实测**；换场地必须改，
     * 否则 Ra 与 ET0 会随之偏。来源：项目标称四川（四川师范大学），纬度按该地取。</p>
     */
    public static final double LATITUDE_DEGREES = 30.7;

    /**
     * 日温差（℃），FAO-56 Hargreaves 式需要。
     *
     * <p>取 12 ℃ 与引擎的室外气温模型一致：{@code outsideTemperature = 17 + 12 × 日照相位}，
     * 即室外日振幅 12 ℃。**该一致性是刻意的**——两处不该各拍一个数。</p>
     */
    public static final double DAILY_TEMPERATURE_RANGE_C = 12.0;
}
